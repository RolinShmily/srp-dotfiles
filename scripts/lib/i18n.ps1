if (-not $Global:DF_Lang) { $Global:DF_Lang = if ($env:DF_LANG) { $env:DF_LANG } else { 'en' } }

function Set-I18nLanguage {
    param([string]$Language = 'en')

    switch ($Language.ToLowerInvariant()) {
        'zh' { $Global:DF_Lang = 'zh' }
        'cn' { $Global:DF_Lang = 'zh' }
        'en' { $Global:DF_Lang = 'en' }
        default {
            Write-Warning "Unsupported language '$Language'; using en."
            $Global:DF_Lang = 'en'
        }
    }
    $env:DF_LANG = $Global:DF_Lang
}

